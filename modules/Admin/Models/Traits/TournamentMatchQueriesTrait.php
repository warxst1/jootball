    /**
     * อัปเดตสถานะแมตช์อัตโนมัติตามวันที่
     * - ถ้าวันที่แข่ง <= วันนี้ และสถานะ = 0 (รอแข่งขัน) → เปลี่ยนเป็น 1 (กำลังแข่งขัน)
     * - ไม่เปลี่ยนสถานะที่เป็น 3 (จบการแข่งขัน) แล้ว
     * @param int $tour_id - รหัสการแข่งขัน (ถ้าไม่ระบุจะอัปเดตทุก tournament)
     * @return int จำนวนแมตช์ที่อัปเดต
     */
    public function autoUpdateMatchStatus($tour_id = null)
    {
        try {
            $today = date('Y-m-d');

            $builder = $this->db->table('tournament_match_result');
            $builder->set('match_status', 1); // กำลังแข่งขัน

            // เงื่อนไข: วันที่แข่ง <= วันนี้ และ สถานะ = รอแข่งขัน (0)
            $builder->where('date <=', $today);
            $builder->where('date IS NOT NULL');
            $builder->where("date != '0000-00-00'");
            $builder->where('match_status', 0);

            // มีทีมครบทั้งสองฝั่ง
            $builder->where('team1_id >', 0);
            $builder->where('team2_id >', 0);

            if ($tour_id) {
                $builder->where('tour_id', $tour_id);
            }

            $builder->update();

            return $this->db->affectedRows();
        } catch (\Exception $e) {
            log_message('error', 'autoUpdateMatchStatus error: ' . $e->getMessage());
            return 0;
        }
    }

    /**
     * สร้างแมตช์แบบลีก (Round-Robin)
     * @param int $tour_id - รหัสการแข่งขัน
     * @param int $num_teams - จำนวนทีม
     * @return array
     */
    function generateLeagueMatches($tour_id, $num_teams)
    {
        if ($num_teams < 2) {
            return [
                'status' => 'error',
                'msg' => 'ต้องมีอย่างน้อย 2 ทีม'
            ];
        }

        $this->db->transBegin();

        try {
            $builder = $this->db->table('tournament_match_result');

            // ลบแมตช์เก่าทั้งหมดของการแข่งขันนี้
            $builder->where('tour_id', $tour_id)->delete();

            $match_number = 1;

            // สร้างแมตช์แบบ Round-Robin (ทุกทีมเจอกันทุกทีม)
            for ($i = 1; $i <= $num_teams; $i++) {
                for ($j = $i + 1; $j <= $num_teams; $j++) {
                    $data = [
                        'tour_id' => $tour_id,
                        'team1_id' => 0, // ยังไม่ได้กำหนดทีม
                        'team2_id' => 0, // ยังไม่ได้กำหนดทีม
                        'team1_score' => null,
                        'team2_score' => null,
                        'result' => null,
                        'match_status' => 0,
                        'match_round' => 'นัดที่ ' . $match_number,
                        'create_by' => session()->get('member_id') ?? 0,
                        'create_date' => date('Y-m-d H:i:s')
                    ];

                    $builder->insert($data);
                    $match_number++;
                }
            }

            $this->db->transCommit();

            return [
                'status' => 'success',
                'msg' => 'สร้างแมตช์สำเร็จ',
                'total_matches' => $match_number - 1
            ];
        } catch (\Exception $e) {
            $this->db->transRollback();
            return [
                'status' => 'error',
                'msg' => 'เกิดข้อผิดพลาด: ' . $e->getMessage()
            ];
        }
    }

    /**
     * สร้างแมตช์แบบทัวร์นาเมนต์ (Knockout)
     * @param int $tour_id - รหัสการแข่งขัน
     * @param int $num_teams - จำนวนทีม (ต้องเป็นกำลัง 2 เช่น 4, 8, 16, 32)
     * @return array
     */
    function generateKnockoutMatches($tour_id, $num_teams)
    {
        // ตรวจสอบว่าจำนวนทีมเป็นกำลัง 2 หรือไม่
        if (!$this->isPowerOfTwo($num_teams)) {
            return [
                'status' => 'error',
                'msg' => 'จำนวนทีมต้องเป็นกำลัง 2 (4, 8, 16, 32)'
            ];
        }

        $this->db->transBegin();

        try {
            $builder = $this->db->table('tournament_match_result');

            // ลบแมตช์เก่าทั้งหมดของการแข่งขันนี้
            $builder->where('tour_id', $tour_id)->delete();

            // คำนวณจำนวนรอบ (เช่น 8 ทีม = 3 รอบ)
            $total_rounds = (int)log($num_teams, 2);
            $round_names = $this->getRoundNames($num_teams);

            $match_number = 1;
            $round_id = 1;

            // สร้างแมตช์สำหรับแต่ละรอบ
            for ($round = 0; $round < $total_rounds; $round++) {
                $matches_in_round = (int)pow(2, $total_rounds - $round - 1);

                for ($match = 0; $match < $matches_in_round; $match++) {
                    $data = [
                        'tour_id' => $tour_id,
                        'team1_id' => 0, // ยังไม่ได้กำหนดทีม
                        'team2_id' => 0, // ยังไม่ได้กำหนดทีม
                        'team1_score' => null,
                        'team2_score' => null,
                        'result' => null,
                        'match_status' => 0,
                        'match_round' => $round_names[$round],
                        'round_id' => $round_id,
                        'create_by' => session()->get('member_id') ?? 0,
                        'create_date' => date('Y-m-d H:i:s')
                    ];

                    $builder->insert($data);
                    $match_number++;
                }
                $round_id++;
            }

            $this->db->transCommit();

            return [
                'status' => 'success',
                'msg' => 'สร้างแมตช์สำเร็จ',
                'total_matches' => $match_number - 1,
                'total_rounds' => $total_rounds
            ];
        } catch (\Exception $e) {
            $this->db->transRollback();
            return [
                'status' => 'error',
                'msg' => 'เกิดข้อผิดพลาด: ' . $e->getMessage()
            ];
        }
    }

    /**
     * ตรวจสอบว่าเลขเป็นกำลัง 2 หรือไม่
     */
    private function isPowerOfTwo($n)
    {
        return ($n > 0) && (($n & ($n - 1)) == 0);
    }

    /**
     * สร้างชื่อรอบตามจำนวนทีม
     */
    private function getRoundNames($num_teams)
    {
        $rounds = [];
        $total_rounds = (int)log($num_teams, 2);

        // กำหนดชื่อรอบจากหลังมาหน้า
        $round_labels = [
            1 => 'รอบชิงชนะเลิศ',
            2 => 'รอบรองชนะเลิศ',
            3 => 'รอบ 8 ทีม',
            4 => 'รอบ 16 ทีม',
            5 => 'รอบ 32 ทีม',
        ];

        for ($i = 0; $i < $total_rounds; $i++) {
            $reverse_index = $total_rounds - $i;
            $rounds[] = $round_labels[$reverse_index] ?? 'รอบที่ ' . ($i + 1);
        }

        return $rounds;
    }

    /**
     * ดึงแมตช์ที่ยังไม่ได้กำหนดทีม
     */
    function getMatchesForTeamAssignment($tour_id)
    {
        $builder = $this->db->table('tournament_match_result');
        $builder->select('*');
        $builder->where('tour_id', $tour_id);
        $builder->orderBy('round_id', 'ASC');
        $builder->orderBy('match_id', 'ASC');
        $result = $builder->get()->getResultArray();
        return $result;
    }

    /**
     * กำหนดทีมให้กับแมตช์
     */
    function assignTeamsToMatch($match_id, $team1_id, $team2_id)
    {
        $builder = $this->db->table('tournament_match_result');
        $builder->set('team1_id', $team1_id);
        $builder->set('team2_id', $team2_id);
        $builder->set('update_by', session()->get('member_id') ?? 0);
        $builder->set('update_date', date('Y-m-d H:i:s'));
        $builder->where('match_id', $match_id);
        $builder->update();

        return [
            'status' => 'success',
            'msg' => 'กำหนดทีมสำเร็จ'
        ];
    }

    /**
     * สร้างแมตช์พร้อมทีมที่จับคู่แล้ว (ใช้ MatchScheduler)
     * @param int $tour_id - รหัสการแข่งขัน
     * @param array $rounds - array ของข้อมูลรอบ
     * @param array $teamIds - array ของ team IDs ที่ลงทะเบียน
     * @return array
     */
    function generateMatchesWithTeams($tour_id, $rounds, $teamsData, $stage_id = null)
    {
        if (empty($rounds) || empty($teamsData)) {
            return [
                'status' => 'error',
                'msg' => 'ข้อมูลไม่ครบถ้วน'
            ];
        }

        // Normalize teamsData to ensure it's an array of objects or IDs
        // If it's a list of IDs (old format), convert to objects with empty group
        if (is_array($teamsData) && !empty($teamsData) && !is_array($teamsData[0])) {
            $teamsData = array_map(function ($id) {
                return ['id' => $id, 'group' => ''];
            }, $teamsData);
        }

        // Sanitize team IDs: convert auto teams and invalid IDs to 0
        $teamsData = array_map(function ($team) {
            $id = $team['id'] ?? 0;
            // If ID is string starting with 'auto_' or is 0/'0' or empty, treat as mock team (0)
            if (is_string($id) && (strpos($id, 'auto_') === 0 || $id === '0' || $id === '')) {
                $id = 0;
            } elseif (!is_numeric($id)) {
                $id = 0;
            } else {
                $id = (int)$id;
            }
            return ['id' => $id, 'group' => $team['group'] ?? ''];
        }, $teamsData);

        // ถ้ามีแค่ mock team (ID=0) ให้สร้าง mock teams อัตโนมัติ
        if (count($teamsData) === 1 && isset($teamsData[0]['id']) && $teamsData[0]['id'] == 0) {
            $teamsData = [
                ['id' => 0, 'group' => 'A'],
                ['id' => 0, 'group' => 'A'],
                ['id' => 0, 'group' => 'B'],
                ['id' => 0, 'group' => 'B']
            ];
        }

        $this->db->transBegin();

        try {
            // Import MatchScheduler library
            $scheduler = new \App\Libraries\MatchScheduler();

            // Collect round names to be regenerated
            $roundNames = [];
            foreach ($rounds as $round) {
                if (!empty($round['name'])) {
                    $roundNames[] = $round['name'];
                }
            }

            // ลบแมตช์เก่าก่อน generate ใหม่
            if (!empty($stage_id)) {
                // มี stage_id → ลบ "ทุก" match ของ stage นี้ (ไม่ผูกกับชื่อ round)
                // กันเคสเปลี่ยนชื่อ round (เช่น "รอบที่ 1" → "Group stage") แล้ว match เก่าชื่อเดิมตกค้าง
                // ทำให้ index คู่แข่งเกินจำนวนทีม → ชื่อทีม resolve ไม่ได้ ("Unknown")
                $this->db->table('tournament_match_result')
                    ->where('tour_id', $tour_id)
                    ->where('stage_id', $stage_id)
                    ->delete();
            } elseif (!empty($roundNames)) {
                // ไม่มี stage_id (legacy) → ลบตามชื่อ round ที่กำลังจะสร้างใหม่
                $this->db->table('tournament_match_result')
                    ->where('tour_id', $tour_id)
                    ->whereIn('match_round', $roundNames)
                    ->delete();
            }

            $totalMatches = 0;
            // Support both regular users and coaches
            $userId = session()->get('member_id') ?? session()->get('coach_user_id') ?? 0;
            $now = date('Y-m-d H:i:s');

            // สร้างแมตช์สำหรับแต่ละรอบ
            foreach ($rounds as $index => $roundData) {
                $roundName = $roundData['name'] ?? '';
                $format = $roundData['type'] ?? 'knockout';
                $numGroups = $roundData['groups'] ?? 1;

                // ใช้ MatchScheduler เพื่อจับคู่แมตช์
                $matchPairs = [];

                // Pair on teams_json slot indexes rather than team ids, then look the
                // ids up when inserting. The schedulers only permute whatever values
                // they are given, so the fixtures come out identical — but every row
                // can now record which slot it belongs to, which is the only thing
                // that keeps a match identifiable after another one is deleted.
                $allSlots = array_keys($teamsData);

                // ตรวจสอบว่าเป็น league_single หรือ league_double
                if ($format === 'league_single' || $format === 'league') {
                    if ($numGroups > 1) {
                        // Group stage - รอบเดียว
                        // Check if we have pre-assigned groups in teamsData
                        $hasGroups = false;
                        foreach ($teamsData as $t) {
                            if (!empty($t['group'])) {
                                $hasGroups = true;
                                break;
                            }
                        }

                        if ($hasGroups) {
                            // Generate matches based on pre-assigned groups
                            $groupedTeams = [];
                            foreach ($teamsData as $slot => $t) {
                                $g = $t['group'] ?: 'A'; // Default to A if missing
                                $groupedTeams[$g][] = $slot;
                            }

                            foreach ($groupedTeams as $groupId => $gTeamIds) {
                                $gMatches = $scheduler->generateRoundRobin($gTeamIds);
                                // Assign group_id to matches
                                foreach ($gMatches as &$m) {
                                    $m['group_id'] = $groupId;
                                }
                                $matchPairs = array_merge($matchPairs, $gMatches);
                            }
                        } else {
                            // Auto-assign groups (old logic)
                            $matchPairs = $scheduler->generateGroupStage($allSlots, $numGroups, false);
                        }
                    } else {
                        // Regular league (round robin) - รอบเดียว
                        $matchPairs = $scheduler->generateRoundRobin($allSlots);
                    }
                } else if ($format === 'league_double') {
                    if ($numGroups > 1) {
                        // Group stage - ไปและกลับ
                        // Check if we have pre-assigned groups in teamsData
                        $hasGroups = false;
                        foreach ($teamsData as $t) {
                            if (!empty($t['group'])) {
                                $hasGroups = true;
                                break;
                            }
                        }

                        if ($hasGroups) {
                            // Generate matches based on pre-assigned groups
                            $groupedTeams = [];
                            foreach ($teamsData as $slot => $t) {
                                $g = $t['group'] ?: 'A'; // Default to A if missing
                                $groupedTeams[$g][] = $slot;
                            }

                            foreach ($groupedTeams as $groupId => $gTeamIds) {
                                $gMatches = $scheduler->generateRoundRobinDouble($gTeamIds);
                                // Assign group_id to matches
                                foreach ($gMatches as &$m) {
                                    $m['group_id'] = $groupId;
                                }
                                $matchPairs = array_merge($matchPairs, $gMatches);
                            }
                        } else {
                            // Group stage - ไปและกลับ (Auto)
                            $matchPairs = $scheduler->generateGroupStage($allSlots, $numGroups, true);
                        }
                    } else {
                        // Regular league (round robin double) - ไปและกลับ
                        $matchPairs = $scheduler->generateRoundRobinDouble($allSlots);
                    }
                } else {
                    // Knockout format
                    $matchPairs = $scheduler->generateKnockout($allSlots);
                }

                // บันทึกแมตช์ พร้อมทีมที่จับคู่แล้ว
                // $pair holds slot indexes; generateKnockout() pads an odd bracket with
                // -1 for a bye, which is not a slot.
                $slotToTeamId = static function ($slot) use ($teamsData) {
                    return isset($teamsData[$slot]) ? (int) $teamsData[$slot]['id'] : 0;
                };
                $slotOrNull = static function ($slot) use ($teamsData) {
                    return isset($teamsData[$slot]) ? (int) $slot : null;
                };

                foreach ($matchPairs as $pair) {
                    $this->db->table('tournament_match_result')->insert([
                        'tour_id' => $tour_id,
                        'stage_id' => $stage_id,  // Link to stage directly
                        'match_round' => $roundName,
                        'group_id' => $pair['group_id'] ?? null,
                        'team1_id' => $slotToTeamId($pair['team1']),
                        'team2_id' => $slotToTeamId($pair['team2']),
                        'team1_slot' => $slotOrNull($pair['team1']),
                        'team2_slot' => $slotOrNull($pair['team2']),
                        'team1_score' => null,
                        'team2_score' => null,
                        'result' => null,
                        'match_status' => 0,
                        'referee' => null,
                        'stadium' => null,
                        'date' => null,
                        'time' => null,
                        'create_by' => $userId,
                        'create_date' => $now,
                        'update_by' => $userId,
                        'update_date' => $now
                    ]);
                    $totalMatches++;
                }
            }

            $this->db->transCommit();

            return [
                'status' => 'success',
                'msg' => "สร้างแมตช์จาก " . count($rounds) . " รอบสำเร็จ",
                'total_matches' => $totalMatches
            ];
        } catch (\Exception $e) {
            $this->db->transRollback();
            return [
                'status' => 'error',
                'msg' => 'เกิดข้อผิดพลาด: ' . $e->getMessage()
            ];
        }
    }
