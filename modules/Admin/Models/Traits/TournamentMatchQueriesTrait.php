    /**
     * Sync stage teams to matches in tournament_match_result
     * This ensures that when teams are selected in the setup UI, the actual matches are updated.
     */
    public function syncStageMatches($stageId, $teams)
    {
        // 1. Get stage details
        $stage = $this->db->table('tournament_stages')
            ->where('stage_id', $stageId)
            ->get()
            ->getRowArray();

        if (!$stage) return false;

        $tourId = $stage['tour_id'];
        $stageName = $stage['stage_name'];
        $format = $stage['format'];

        // 2. Get matches for this stage
        // Use stage_id if possible for more accuracy
        $builder = $this->db->table('tournament_match_result')
            ->where('tour_id', $tourId);

        if (!empty($stageId)) {
            // Check if there are matches with this stage_id
            $count = $this->db->table('tournament_match_result')
                ->where('stage_id', $stageId)
                ->countAllResults();

            if ($count > 0) {
                $builder->where('stage_id', $stageId);
            } else {
                // Fallback to match_round (legacy or not yet linked)
                $builder->where('match_round', $stageName);
            }
        } else {
            $builder->where('match_round', $stageName);
        }

        $matches = $builder->orderBy('match_id', 'ASC')
            ->get()
            ->getResultArray();

        if (empty($matches)) return false;

        // 3. Work out the fixture list as *slot pairs*, then match it against the rows.
        //
        // The old code lined the generated pairs up with the rows by running index.
        // That identity is destroyed by a single deletion: every later row shifts and
        // ends up carrying a different fixture, the tail fixtures fall off the end and
        // can never be written again, and the labels the UI derives from row order all
        // move up one. Rows now record the slots they belong to, so they can be matched
        // by identity instead of by position.
        $expectedByGroup = $this->buildStageSlotPairs($teams, $format);

        // Team id sitting in a slot right now; a slot with nothing picked stays 0.
        $idForSlot = static function ($slot) use ($teams) {
            $id = ($slot !== null && isset($teams[$slot])) ? ($teams[$slot]['id'] ?? 0) : 0;
            if (is_string($id) && (strpos($id, 'auto_') === 0 || $id === '0' || $id === '')) {
                return 0;
            }
            return is_numeric($id) ? (int) $id : 0;
        };

        $allRowsKnowTheirSlots = true;
        foreach ($matches as $m) {
            if ($m['team1_slot'] === null || $m['team2_slot'] === null) {
                $allRowsKnowTheirSlots = false;
                break;
            }
        }

        if ($allRowsKnowTheirSlots) {
            $expectedKeys = [];
            foreach ($expectedByGroup as $pairs) {
                foreach ($pairs as $pair) {
                    $expectedKeys[$this->slotPairKey($pair[0], $pair[1])] = true;
                }
            }

            $surplus = [];
            $matched = [];
            foreach ($matches as $m) {
                // A row whose slot pair is no longer in the fixture list belongs to a
                // slot that was removed, so it goes. Rows are never re-created here:
                // fixtures pruned by hand only come back on a fresh Generate.
                if (isset($expectedKeys[$this->slotPairKey($m['team1_slot'], $m['team2_slot'])])) {
                    $matched[] = $m;
                } else {
                    $surplus[] = $m;
                }
            }

            // Not one row recognised means the fixture list does not describe this
            // stage at all (a stage generated by a different pairing routine, say),
            // not that every match became obsolete. Touch nothing rather than wipe it.
            if (empty($matched) && !empty($expectedKeys)) {
                log_message(
                    'warning',
                    '[syncStageMatches] stage_id=' . $stageId . ' has ' . count($matches)
                        . ' rows but none of them matches the expected fixture list; skipped.'
                );
                return false;
            }

            foreach ($matched as $m) {
                // Written in the row's own slot order, so a manual swap survives.
                $this->db->table('tournament_match_result')
                    ->where('match_id', $m['match_id'])
                    ->update([
                        'team1_id' => $idForSlot($m['team1_slot']),
                        'team2_id' => $idForSlot($m['team2_slot']),
                    ]);
            }

            $this->deleteSurplusStageMatches($surplus, $stageId, '');

            return true;
        }

        // Rows predating the slot columns cannot be matched by identity yet. Fall back
        // to the positional alignment, and stamp the slots on as we go so the next sync
        // takes the branch above.
        $matchesByGroup = [];
        foreach ($matches as $m) {
            $matchesByGroup[(string) ($m['group_id'] ?? '')][] = $m;
        }

        // Per-group alignment only works when every expected group is actually
        // represented in the rows. Single-group stages and legacy rows saved
        // without a group_id fall back to one flat list.
        $perGroup = count($expectedByGroup) > 1;
        if ($perGroup) {
            foreach (array_keys($expectedByGroup) as $groupId) {
                if (empty($matchesByGroup[(string) $groupId])) {
                    $perGroup = false;
                    break;
                }
            }
        }

        if (!$perGroup) {
            $allPairs = [];
            foreach ($expectedByGroup as $pairs) {
                $allPairs = array_merge($allPairs, $pairs);
            }
            $expectedByGroup = ['' => $allPairs];
            $matchesByGroup  = ['' => $matches];
        }

        foreach ($expectedByGroup as $groupId => $pairs) {
            $groupMatches = $matchesByGroup[(string) $groupId] ?? [];

            if (count($groupMatches) < count($pairs)) {
                log_message(
                    'warning',
                    '[syncStageMatches] stage_id=' . $stageId . ' group="' . $groupId . '" has '
                        . count($groupMatches) . ' match rows but ' . count($pairs)
                        . ' fixtures are expected — the surplus fixtures cannot be assigned.'
                );
            }

            foreach ($pairs as $i => $pair) {
                if (!isset($groupMatches[$i])) break;

                // Scores/results/schedule stay as-is.
                $this->db->table('tournament_match_result')
                    ->where('match_id', $groupMatches[$i]['match_id'])
                    ->update([
                        'team1_id'   => $idForSlot($pair[0]),
                        'team2_id'   => $idForSlot($pair[1]),
                        'team1_slot' => $pair[0],
                        'team2_slot' => $pair[1],
                    ]);
            }

            // Teams removed from teams_json shrink the fixture list. Updating only the
            // first N rows would keep the removed teams visible on the surplus rows.
            $this->deleteSurplusStageMatches(array_slice($groupMatches, count($pairs)), $stageId, $groupId);
        }

        // Lowering the group count leaves whole groups behind (4 groups -> 2 makes
        // C and D orphans). Rows without a group_id are skipped: they cannot be
        // attributed to a group, so deleting them would be a guess.
        foreach ($matchesByGroup as $groupId => $groupMatches) {
            if ((string) $groupId === '' || isset($expectedByGroup[$groupId])) continue;

            $this->deleteSurplusStageMatches($groupMatches, $stageId, $groupId);
        }

        return true;
    }

    /**
     * The fixture list of a stage, expressed as pairs of teams_json slot indexes.
     *
     * Slots are paired instead of team ids because a slot keeps its identity even
     * when it holds no team yet, which is what lets a row stay recognisable after
     * its neighbours are deleted. The schedulers only permute the values handed to
     * them, so feeding them slot indexes yields exactly the same fixtures as
     * feeding them team ids.
     *
     * @return array group id => list of [slotA, slotB]; slotB is null for a bye
     */
    protected function buildStageSlotPairs(array $teams, $format)
    {
        if ($format === 'knockout') {
            $pairs = [];
            for ($i = 0; $i < count($teams); $i += 2) {
                $pairs[] = [$i, isset($teams[$i + 1]) ? $i + 1 : null];
            }
            return ['' => $pairs];
        }

        $scheduler = new \App\Libraries\MatchScheduler();

        $slotsByGroup = [];
        foreach ($teams as $i => $t) {
            $g = !empty($t['group']) ? (string) $t['group'] : 'A';
            $slotsByGroup[$g][] = $i;
        }

        // Sort groups alphabetically to match generation order (A, B, C...)
        ksort($slotsByGroup);

        $out = [];
        foreach ($slotsByGroup as $groupId => $slots) {
            if (count($slots) < 2) {
                $out[$groupId] = [];
                continue;
            }

            $positions = range(0, count($slots) - 1);
            $generated = $format === 'league_double'
                ? $scheduler->generateRoundRobinDouble($positions)
                : $scheduler->generateRoundRobin($positions);

            $out[$groupId] = array_map(
                static fn($m) => [$slots[$m['team1']], $slots[$m['team2']]],
                $generated
            );
        }

        return $out;
    }

    /**
     * Order-independent key for a slot pair, so a row and a fixture still match
     * after the two sides have been swapped.
     */
    protected function slotPairKey($a, $b)
    {
        $a = $a === null ? -1 : (int) $a;
        $b = $b === null ? -1 : (int) $b;

        return $a <= $b ? $a . '-' . $b : $b . '-' . $a;
    }

    /**
     * Drop match rows that the current slot list no longer covers.
     *
     * Called by syncStageMatches() when a stage ends up with more rows than the
     * teams in teams_json can fill — i.e. a team was removed. The reverse case
     * (fewer rows than pairs) is left alone on purpose: those rows were pruned by
     * hand after generating, and only a fresh Generate is allowed to bring them back.
     *
     * A match that has already been played is never dropped here. Losing a recorded
     * result as a side effect of editing the team list would be unrecoverable, so
     * those rows are kept and logged for an admin to deal with by hand.
     *
     * @param array $rows Match rows to delete
     * @return int Number of match rows deleted
     */
    protected function deleteSurplusStageMatches(array $rows, $stageId = null, $groupId = '')
    {
        if (empty($rows)) return 0;

        $played = [];
        $rows = array_filter($rows, static function ($row) use (&$played) {
            $hasResult = $row['team1_score'] !== null || $row['team2_score'] !== null
                || (int) ($row['match_status'] ?? 0) !== 0;

            if ($hasResult) $played[] = $row['match_id'];

            return !$hasResult;
        });

        if (!empty($played)) {
            log_message(
                'warning',
                '[syncStageMatches] stage_id=' . $stageId . ' group="' . $groupId . '" kept '
                    . count($played) . ' surplus match(es) because they already have a result: '
                    . implode(',', $played)
            );
        }

        if (empty($rows)) return 0;

        $matchIds = array_column($rows, 'match_id');

        // Children first, so removing a pair here does not leave orphans behind.
        foreach (['tournament_match_event', 'player_to_match', 'player_match_state'] as $table) {
            $this->db->table($table)->whereIn('match_id', $matchIds)->delete();
        }

        $this->db->table('tournament_match_result')->whereIn('match_id', $matchIds)->delete();

        log_message(
            'info',
            '[syncStageMatches] stage_id=' . $stageId . ' group="' . $groupId . '" deleted '
                . count($matchIds) . ' surplus match(es) after teams were removed: '
                . implode(',', $matchIds)
        );

        return count($matchIds);
    }

    public function getBracketData($tour_id)
    {
        $this->table = "tournament_match_result";
        $builder = $this->db->table($this->table);
        $builder->select($this->table . ".*,
        t1.name as home_team_name, t1.logo as home_team_logo, t2.name as away_team_name, t2.logo as away_team_logo");
        $builder->join("team as t1", "t1.id = $this->table.team1_id", "left");
        $builder->join("team as t2", "t2.id = $this->table.team2_id", "left");

        $matches = [];
        if ($tour_id) {
            $builder->where('tour_id', $tour_id);
            $matches = $builder->get()->getResultArray();
        }
        // echo $this->db->getLastQuery();
        // die();

        $teams = [];
        $scorePairs = [];

        // Validate bracket structure before processing
        // A valid bracket must have 2^n - 1 matches (1, 3, 7, 15, 31, ...)
        $totalMatches = count($matches);

        if ($totalMatches > 0) {
            // Check if it's a valid bracket structure
            $expectedMatchCount = pow(2, log($totalMatches + 1, 2)) - 1;

            if ($totalMatches !== $expectedMatchCount) {
                // Invalid bracket structure, return empty
                return [
                    'teams' => [],
                    'results' => [],
                    'error' => "โครงสร้างแมตช์ไม่ถูกต้อง. ควรมี {$expectedMatchCount} คู่แมตช์แต่มี {$totalMatches} คู่"
                ];
            }
        }

        // ดึงทีมจาก 4 คู่แรก (ถ้ามี 7 แมตช์ → แสดงว่ามี 8 ทีม → รอบแรก = 4 คู่)
        $firstRoundMatchCount = (count($matches) + 1) / 2;

        $logo_1 = '';
        foreach ($matches as $index => $match) {
            if ($index < $firstRoundMatchCount) {
                if (file_exists('./' . $match['home_team_logo'])) {
                    $logo_1 = '<img class="" src="' . base_url($match['home_team_logo']) . '" alt="" width="20" style="vertical-align: left;">';
                } else {
                    $logo_1 = '<img class="" src="' . base_url('/public/img/jootball_logo.png') . '" alt="" width="20" style="vertical-align: left;">';
                }

                if (file_exists('./' . $match['away_team_logo'])) {
                    $logo_2 = '<img class="" src="' . base_url($match['away_team_logo']) . '" alt="" width="20" style="vertical-align: left;">';
                } else {
                    $logo_2 = '<img class="" src="' . base_url('/public/img/jootball_logo.png') . '" alt="" width="20" style="vertical-align: left;">';
                }

                $teams[] = [
                    $logo_1 .  $match['home_team_name'],
                    $logo_2 .  $match['away_team_name']
                ];
            }

            $scorePairs[] = [
                (int)$match['team1_score'],
                (int)$match['team2_score']
            ];
        }


        $rounds = [];
        $remainingScores = $scorePairs;

        // คำนวณจำนวนรอบทั้งหมด
        $totalMatches = count($scorePairs); // เช่น 7
        $totalRounds = (int)log($totalMatches + 1, 2); // เช่น 3 รอบ

        for ($round = 0; $round < $totalRounds; $round++) {
            $matchCountInRound = (int)pow(2, $totalRounds - $round - 1);
            $roundData = array_splice($remainingScores, 0, $matchCountInRound);
            $rounds[] = $roundData;
        }

        $minimalData = [
            'teams' => $teams,
            'results' => $rounds
        ];

        return $minimalData;
    }

